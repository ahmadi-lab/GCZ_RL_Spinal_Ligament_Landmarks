"""Extract journal-paper Tables 1-4 (dissertation Table 4.2 = paper Table 3) from the outputs
regenerated by run_original_notebook.py and check them against the published values.

Source cells of the original notebook:
  Table 1  dataset organisation             cell 9
  Table 2  bone alignment (mean NND)        cell 34, section 1 (9 primary cases)
  Table 3  correspondence strategies        cell 39 (A: pure Hungarian), cell 41 (B: v5, D: v8d)
  Table 4  per-ligament initial/final MAE   cell 41, section 2
Writes outputs/tables/*.csv and outputs/tables/check_against_paper.csv.
"""
from __future__ import annotations

import re
from pathlib import Path

import pandas as pd

HERE = Path(__file__).resolve().parent
CELLS = HERE / "outputs" / "cell_outputs"
TAB = HERE / "outputs" / "tables"
NUM = r"([-+]?\d+\.\d+|\d+)"


def cell(i: int) -> str:
    return (CELLS / f"cell_{i:02d}.txt").read_text(encoding="utf-8")


def strategy_row(text: str, label: str) -> list[float]:
    line = next(l for l in text.splitlines() if l.strip().startswith(label))
    return [float(x) for x in re.findall(NUM, line[len(label) + line.index(label):].replace("%", ""))]


def main():
    TAB.mkdir(parents=True, exist_ok=True)
    checks = []

    def check(table, item, got, paper):
        checks.append({"table": table, "item": item, "regenerated": got, "paper": paper,
                       "matches": abs(float(got) - float(paper)) < 1e-9})

    # Table 1
    t1 = cell(9)
    (TAB / "table_1_dataset.txt").write_text(t1, encoding="utf-8")
    for label, val in [("Curated annotated vertebrae", 57), ("Calibration specimens", 20), ("Held-out partition", 37)]:
        check("1", label, int(re.search(rf"{label}\s+(\d+)", t1).group(1)), val)

    # Table 2
    c34 = cell(34)
    nnd = pd.DataFrame([dict(zip(["case", "mean_nnd_mm", "median_mm", "p95_mm", "max_mm"],
                                 [m[0]] + [float(x) for x in m[1:]]))
                        for m in re.findall(r"^\s+(Verse\S+)\s+([\d.]+)mm\s+([\d.]+)mm\s+([\d.]+)mm\s+([\d.]+)mm", c34, re.M)])
    nnd.to_csv(TAB / "table_2_alignment_per_case.csv", index=False)
    overall = float(re.search(r"Overall mean\s+([\d.]+)mm", c34).group(1))
    check("2", "mean surface distance (mm)", overall, 1.84)
    check("2", "max per-case mean < 5 mm", int(nnd.mean_nnd_mm.max() < 5), 1)

    # Table 3 (= dissertation Table 4.2)
    c39, c41 = cell(39), cell(41)
    pairs = {k: int(v) for k, v in re.findall(r"\b([A-Z]|v5|v8d)=(\d+)", c39 + c41)}
    a = strategy_row(c39, "A — Pure Euclidean Hungarian")          # MAE SD RMSE Max Pass N>10 N>5
    b = strategy_row(c41, "B — v5  (baseline)")                    # MAE SD RMSE Max Pass N>10 N>5
    d = strategy_row(c41, "D — v8d (v5 + ALL+PLL z-band)")
    t3 = pd.DataFrame([
        {"strategy": "Pure Euclidean Hungarian", "pairs": pairs["A"], "MAE": a[0], "SD": a[1], "RMSE": a[2], "Pass5_percent": a[4], "N_gt_10mm": int(a[5])},
        {"strategy": "Initial anatomy-aware matching", "pairs": pairs["v5"], "MAE": b[0], "SD": b[1], "RMSE": b[2], "Pass5_percent": b[4], "N_gt_10mm": int(b[5])},
        {"strategy": "Final anatomy-constrained GCZ", "pairs": pairs["v8d"], "MAE": d[0], "SD": d[1], "RMSE": d[2], "Pass5_percent": d[4], "N_gt_10mm": int(d[5])}])
    t3.to_csv(TAB / "table_3_correspondence_strategies__dissertation_table_4_2.csv", index=False)
    paper3 = [(1126, 4.85, 5.99, 7.71, 75.2, 119), (1039, 3.84, 4.30, 5.76, 80.2, 61), (1042, 3.67, 3.87, 5.34, 82.2, 58)]
    for (_, r), p in zip(t3.iterrows(), paper3):
        for col, v in zip(["pairs", "MAE", "SD", "RMSE", "Pass5_percent", "N_gt_10mm"], p):
            check("3", f"{r.strategy}: {col}", r[col], v)

    # Table 4
    sec = c41.split("PER-LIGAMENT")[1].split("LONG-LINE")[0]
    t4 = pd.DataFrame([{"ligament": m[0], "initial_MAE": float(m[1]), "final_MAE": float(m[2]), "N_gt_10mm_final": int(m[5])}
                       for m in re.findall(r"^\s+(ALL|PLL|LF|ISL|SSL|ITL|CL)\s+([\d.]+)\s+([\d.]+)\s+([-+\d.]+)\s+(\d+)\s+(\d+)", sec, re.M)])
    t4.to_csv(TAB / "table_4_per_ligament_mae.csv", index=False)
    paper4 = {"ALL": (5.07, 4.17, 13), "PLL": (3.70, 3.62, 3), "LF": (3.21, 3.21, 14), "ISL": (4.43, 4.43, 15),
              "SSL": (1.86, 1.86, 0), "ITL": (2.68, 2.68, 0), "CL": (3.36, 3.36, 13)}
    for _, r in t4.iterrows():
        for col, v in zip(["initial_MAE", "final_MAE", "N_gt_10mm_final"], paper4[r.ligament]):
            check("4", f"{r.ligament}: {col}", r[col], v)

    chk = pd.DataFrame(checks)
    chk.to_csv(TAB / "check_against_paper.csv", index=False)
    print(chk.to_string(index=False))
    print(f"\n{int(chk.matches.sum())}/{len(chk)} published values reproduced")


if __name__ == "__main__":
    main()
